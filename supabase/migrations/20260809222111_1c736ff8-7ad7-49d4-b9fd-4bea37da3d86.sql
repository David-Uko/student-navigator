CREATE TABLE public.students (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name text NOT NULL,
  matric_number text NOT NULL UNIQUE,
  department text NOT NULL,
  level text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.students TO authenticated;
GRANT ALL ON public.students TO service_role;
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Authenticated users can view students" ON public.students FOR SELECT TO authenticated USING (true);
CREATE POLICY "Authenticated users can add students" ON public.students FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Authenticated users can update students" ON public.students FOR UPDATE TO authenticated USING (true);

CREATE TABLE public.performance_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  semester text NOT NULL,
  attendance_rate numeric NOT NULL,
  avg_test_score numeric NOT NULL,
  study_habits_score numeric NOT NULL,
  predicted_score numeric NOT NULL,
  risk_band text NOT NULL,
  actual_score numeric,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX performance_records_student_id_idx ON public.performance_records(student_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.performance_records TO authenticated;
GRANT ALL ON public.performance_records TO service_role;
ALTER TABLE public.performance_records ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Authenticated users can view records" ON public.performance_records FOR SELECT TO authenticated USING (true);
CREATE POLICY "Authenticated users can add records" ON public.performance_records FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Authenticated users can update records" ON public.performance_records FOR UPDATE TO authenticated USING (true);

